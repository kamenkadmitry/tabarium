/** Every key the picker offers, for validation and tests. */
export const ALL_ICON_KEYS: readonly string[] = ICON_GROUPS.flatMap((g) => g.icons.map((i) => i.key));

export const isKnownIcon = (key: string): boolean => ALL_ICON_KEYS.includes(key);

interface Props {
  /** Stored icon key, or null to show the first letter of the name. */
  icon: string | null;
  name: string;
  size?: number;
  className?: string;
}

/** The icon of a space, or the first letter of its name when it has none. */
export function SpaceIcon({ icon, name, size = 20, className = '' }: Props) {
  const [kind, id] = icon?.split(':') ?? [];
  if (kind === 'lucide' && id !== undefined) {
    const entry = LUCIDE[id];
    if (entry) return <entry.icon size={size} aria-hidden className={`shrink-0 ${className}`} />;
  }
  if (kind === 'brand' && id !== undefined) {
    const brand = BRANDS[id];
    if (brand) {
      return (
        <svg viewBox="0 0 24 24" width={size} height={size} aria-hidden fill="currentColor" className={`shrink-0 ${className}`}>
          <path d={brand.path} />
        </svg>
      );
    }
  }
  return (
    <span aria-hidden className={`grid shrink-0 place-items-center font-bold ${className}`} style={{ width: size, height: size, fontSize: Math.round(size * 0.6) }}>
      {name[0]?.toUpperCase()}
    </span>
  );
}
